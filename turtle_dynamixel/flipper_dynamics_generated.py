def limb_dynamics(side, q, dq, medium="air", gravity=GRAVITY, buoyancy_scale=1.0, added_mass_scale=1.0):
    """
    M(q), C(q, dq) and g(q) of one front limb.
    Arguments:
        side: "left" or "right"
        q, dq: joint positions and velocities of the limb, shape (3,)
        medium: "air" or "water". In water, g includes buoyancy and M, C include the added mass of the blade.
        gravity: gravity vector in the shell frame, shape (3,)
        buoyancy_scale: scales the displaced water mass of the links
        added_mass_scale: scales the added mass of the flipper blade
    Returns:
        M: mass matrix, shape (3, 3)
        C: Coriolis matrix, shape (3, 3), with dM/dt - 2C skew-symmetric
        g: torques that hold the limb still against gravity (and buoyancy), shape (3,)
    """
    M_fn, C_fn, G_fn, M_add_fn, C_add_fn, link_mass, link_com, buoyant_mass, cob = _LIMB[side]
    M = M_fn(q)
    C = C_fn(q, dq)
    g = G_fn(q, link_mass, link_com, gravity)
    if medium == "water":
        M = M + added_mass_scale * M_add_fn(q)
        C = C + added_mass_scale * C_add_fn(q, dq)
        g = g + G_fn(q, -buoyancy_scale * buoyant_mass, cob, gravity)
    elif medium != "air":
        raise ValueError(f"Unknown medium {medium}")
    return M, C, g


def mass(q, dq, medium="air", gravity=GRAVITY):
    """
    Drop-in replacement for the old mass.py: M, C and G of both front limbs.
    Arguments:
        q, dq: joint positions and velocities [L1, L2, L3, R1, R2, R3] in the MuJoCo convention, shape (6,) or (6, 1).
            Unlike the old mass.py, no offset is subtracted: map motor angles to this convention first.
    Returns:
        M: block-diagonal mass matrix, shape (6, 6)
        C: block-diagonal Coriolis matrix, shape (6, 6)
        G: gravity torques, shape (6,)
    """
    q = np.asarray(q, dtype=float).reshape(-1)
    dq = np.asarray(dq, dtype=float).reshape(-1)
    M_l, C_l, g_l = limb_dynamics("left", q[:3], dq[:3], medium, gravity)
    M_r, C_r, g_r = limb_dynamics("right", q[3:6], dq[3:6], medium, gravity)
    M = np.zeros((6, 6))
    C = np.zeros((6, 6))
    M[:3, :3], M[3:, 3:] = M_l, M_r
    C[:3, :3], C[3:, 3:] = C_l, C_r
    return M, C, np.concatenate([g_l, g_r])
